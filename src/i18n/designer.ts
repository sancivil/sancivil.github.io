/** Arabic counted nouns: 1 and 2 have their own forms, 3–10 take the plural, 11 and up the singular. */
const arCount = (one: string, two: string, few: string, many: string, hundred = many) => (n: number) => {
  if (n === 1) return one;
  if (n === 2) return two;
  const r = n % 100;
  return `${n} ${r >= 3 && r <= 10 ? few : r >= 11 || n < 100 ? many : hundred}`;
};
